    public static IEnumerable<Tuple<string, string, string, string, string, string>> GetValues()
    {
        //GlyphTypeface.CharacterToGlyphMap
        foreach (var item in typeof(FontIcons).GetFields())
        {
            var value = item.GetValue(null)?.ToString();
            int codePoint = char.ConvertToUtf32(value, 0);
            string htmlEntity = $"&#x{codePoint:X};";
            string code = $"\\x{codePoint:X}";
            yield return Tuple.Create(item.Name, value, "{" + $"x:Static FontIcons.{item.Name}" + "}", $"FontIcons.{item.Name}", $"{code}", $"{htmlEntity}");
        }
    }
